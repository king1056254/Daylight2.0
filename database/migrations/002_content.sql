CREATE TABLE IF NOT EXISTS blog_posts (
  id CHAR(36) NOT NULL PRIMARY KEY,
  title VARCHAR(250) NOT NULL, slug VARCHAR(250) NOT NULL, excerpt TEXT NULL, body MEDIUMTEXT NULL,
  category VARCHAR(100) NULL, tags JSON NULL, cover_url VARCHAR(500) NULL, author_name VARCHAR(200) NULL,
  published TINYINT(1) NOT NULL DEFAULT 0, published_at TIMESTAMP NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_blog_slug (slug), KEY idx_blog_pub (published, published_at)
