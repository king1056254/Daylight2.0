-- Public content tables (ported from the original Supabase schema). text[] columns become JSON.
CREATE TABLE IF NOT EXISTS services (
  id CHAR(36) NOT NULL PRIMARY KEY,
  title VARCHAR(200) NOT NULL, slug VARCHAR(200) NOT NULL, summary TEXT NULL, description MEDIUMTEXT NULL,
  icon VARCHAR(60) NULL, features JSON NULL, sort_order INT NOT NULL DEFAULT 0, published TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_services_slug (slug), KEY idx_services_pub (published, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS industries (
  id CHAR(36) NOT NULL PRIMARY KEY,
  name VARCHAR(200) NOT NULL, slug VARCHAR(200) NOT NULL, summary TEXT NULL, description MEDIUMTEXT NULL,
  icon VARCHAR(60) NULL, sort_order INT NOT NULL DEFAULT 0, published TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_industries_slug (slug), KEY idx_industries_pub (published, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS technologies (
  id CHAR(36) NOT NULL PRIMARY KEY,
  name VARCHAR(200) NOT NULL, category VARCHAR(100) NOT NULL DEFAULT 'Backend', sort_order INT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_technologies_pub (published, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS portfolio_projects (
  id CHAR(36) NOT NULL PRIMARY KEY,
  title VARCHAR(200) NOT NULL, slug VARCHAR(200) NOT NULL, client_name VARCHAR(200) NULL, industry VARCHAR(200) NULL,
  summary TEXT NULL, problem MEDIUMTEXT NULL, solution MEDIUMTEXT NULL, outcome MEDIUMTEXT NULL,
  technologies JSON NULL, features JSON NULL, status VARCHAR(40) NOT NULL DEFAULT 'Live',
  live_url VARCHAR(500) NULL, cover_url VARCHAR(500) NULL, featured TINYINT(1) NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0, published TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_portfolio_slug (slug), KEY idx_portfolio_pub (published, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS saas_products (
  id CHAR(36) NOT NULL PRIMARY KEY,
  name VARCHAR(200) NOT NULL, slug VARCHAR(200) NOT NULL, tagline VARCHAR(300) NULL, description MEDIUMTEXT NULL,
  features JSON NULL, status VARCHAR(40) NOT NULL DEFAULT 'Coming Soon', product_url VARCHAR(500) NULL, cover_url VARCHAR(500) NULL,
  sort_order INT NOT NULL DEFAULT 0, published TINYINT(1) NOT NULL DEFAULT 1,
