CREATE TABLE IF NOT EXISTS job_openings (
  id CHAR(36) NOT NULL PRIMARY KEY,
  title VARCHAR(200) NOT NULL, slug VARCHAR(200) NOT NULL, department VARCHAR(100) NULL, location VARCHAR(200) NULL,
  employment_type VARCHAR(60) NULL DEFAULT 'Full-time', description MEDIUMTEXT NULL, requirements JSON NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'Open',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_jobs_slug (slug), KEY idx_jobs_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS company_settings (
  id CHAR(36) NOT NULL PRIMARY KEY,
  company_name VARCHAR(200) NOT NULL DEFAULT 'Daylight', tagline VARCHAR(300) NULL, description TEXT NULL,
  email VARCHAR(254) NULL, phone VARCHAR(40) NULL, address VARCHAR(300) NULL, whatsapp VARCHAR(40) NULL,
  linkedin_url VARCHAR(500) NULL, twitter_url VARCHAR(500) NULL, github_url VARCHAR(500) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Lead tables (public forms write here)
CREATE TABLE IF NOT EXISTS contact_messages (
  id CHAR(36) NOT NULL PRIMARY KEY,
  name VARCHAR(300) NOT NULL, email VARCHAR(254) NOT NULL, phone VARCHAR(40) NULL, company VARCHAR(300) NULL,
  subject VARCHAR(300) NULL, message TEXT NOT NULL, status VARCHAR(40) NOT NULL DEFAULT 'New',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_contact_status (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS quote_requests (
  id CHAR(36) NOT NULL PRIMARY KEY,
  name VARCHAR(300) NOT NULL, email VARCHAR(254) NOT NULL, phone VARCHAR(40) NULL, company VARCHAR(300) NULL,
  country VARCHAR(300) NULL DEFAULT 'Kenya', project_type VARCHAR(100) NULL, budget_range VARCHAR(100) NULL,
  timeline VARCHAR(100) NULL, details TEXT NULL, status VARCHAR(40) NOT NULL DEFAULT 'New',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_quote_status (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS job_applications (
  id CHAR(36) NOT NULL PRIMARY KEY,
  job_id CHAR(36) NULL, name VARCHAR(300) NOT NULL, email VARCHAR(254) NOT NULL, phone VARCHAR(40) NULL,
  portfolio_url VARCHAR(500) NULL, cover_letter TEXT NULL, cv_url VARCHAR(500) NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'Received', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_applications_status (status, created_at),
  CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES job_openings(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
